// Generates types/api.d.ts from The Backend's OpenAPI spec. The spec URL comes from
// BACKEND_SPEC_URL, or is derived from BACKEND_API_URL (`…/api` → `…/docs/api.json`).
// Run through `pnpm api:types`, which loads `.env`.
import { writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'
import { specUrlFrom } from './spec-url.mjs'

const specUrl = specUrlFrom(process.env)

if (!specUrl) {
  console.error('Set BACKEND_API_URL (or BACKEND_SPEC_URL) in .env to generate the API types.')
  process.exit(1)
}

const output = new URL('../types/api.d.ts', import.meta.url)
const spec = await (await fetch(specUrl)).json()
const ast = await openapiTS(spec)

const banner = `/**\n * Generated by scripts/generate-api-types.mjs from The Backend's OpenAPI spec. Do not edit by hand.\n */\n\n`

await writeFile(output, banner + astToString(ast))
// A copy of the spec, which the mock backend serves so the contract suite can run without The Backend.
await writeFile(
  new URL('../types/openapi.json', import.meta.url),
  `${JSON.stringify(spec, null, 2)}\n`,
)
console.log(`Generated types/api.d.ts and types/openapi.json from ${specUrl}`)
